const DICTIONARIES: Record<LocaleId, Record<TranslationKey, string>> = {
  'zh-TW': zhTW,
  'zh-CN': zhCN,
  en,
  ja,
};

export function translate(
  locale: LocaleId,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const dict = DICTIONARIES[locale] ?? DICTIONARIES['zh-TW'];
  let text = dict[key] ?? DICTIONARIES['zh-TW'][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

interface I18nContextValue {
  locale: LocaleId;
  setLocale: (next: LocaleId) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue>({
  locale: 'zh-TW',
  setLocale: () => {},
  t: (key, vars) => translate('zh-TW', key, vars),
});

export const I18nProvider: React.FC<{
  locale: LocaleId;
  onChangeLocale: (next: LocaleId) => void;
  children: React.ReactNode;
}> = ({ locale, onChangeLocale, children }) => {
  const t = React.useCallback(
    (key: TranslationKey, vars?: Record<string, string | number>) => translate(locale, key, vars),
    [locale]
  );

  return (
    <I18nContext.Provider value={{ locale, setLocale: onChangeLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

